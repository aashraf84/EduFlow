export const useERPStore = create<ERPState>((set, get) => ({
  activeModule: 'dashboard',
  setActiveModule: (module) => set({ activeModule: module }),
  sidebarOpen: true,
  setSidebarOpen: (open) => set({ sidebarOpen: open }),
  copilotOpen: false,
  setCopilotOpen: (open) => set({ copilotOpen: open }),
  selectedCampus: 'all',
  setSelectedCampus: (campus) => set({ selectedCampus: campus }),
  // Auth
  user: null,
  isAuthenticated: false,
  isAuthLoading: true,
  setUser: (user) => set({ user, isAuthenticated: !!user, isAuthLoading: false }),
  setAuthLoading: (loading) => set({ isAuthLoading: loading }),
  isViewer: () => {
    const state = get()
    return state.user?.role === 'viewer' || state.user?.role === 'demo'
  },
  // Report settings
  reportSettings: defaultReportSettings,
  setReportSettings: (settings) => set((state) => ({
    reportSettings: { ...state.reportSettings, ...settings }
  })),
}))
